-- =====================================================================
-- SISTEMA DE GERENCIAMENTO DE ALUGUÉIS — MODELO REFATORADO (PostgreSQL)
-- Variante: PESSOA + USUÁRIO em uma única tabela (`usuarios`)
-- =====================================================================
-- Convenções:
--   - PK bigint identity (compatível com o schema atual).
--   - Dinheiro em numeric(12,2). Nunca float.
--   - Enums via text + CHECK. Troque por CREATE TYPE ... AS ENUM se
--     quiser tipagem forte no banco.
--   - `usuarios` guarda cadastro + autenticação. senha_hash/perfil são
--     NULL para quem não loga (proprietário, fiador). A identidade real
--     da linha é `documento`. Papéis de negócio (proprietário/inquilino/
--     fiador) são RELACIONAMENTOS, nunca colunas booleanas.
-- =====================================================================

-- =====================================================================
-- RESET — apaga TODAS as tabelas deste modelo (e TODOS os dados!).
-- Destrutivo e irreversível. Roda antes de recriar tudo do zero.
-- CASCADE derruba FKs, índices e triggers dependentes junto.
-- =====================================================================
DROP TABLE IF EXISTS
  public.pagamentos,
  public.boletos,
  public.parcela_lancamentos,
  public.parcelas,
  public.reajustes,
  public.garantia_seguro_fianca,
  public.garantia_fiadores,
  public.garantia_caucao,
  public.garantias,
  public.contrato_fiadores,   -- substituída por garantia_fiadores (migration 001)
  public.contrato_inquilinos,
  public.contratos,
  public.imoveis,
  public.contas_bancarias,
  public.codigo_verificacao,
  public.usuarios,
  public.pessoas,          -- caso exista de uma versão anterior do modelo
  public.enderecos
CASCADE;

DROP FUNCTION IF EXISTS public.set_updated_at() CASCADE;
DROP FUNCTION IF EXISTS public.valida_caucao_dinheiro() CASCADE;

-- =====================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;


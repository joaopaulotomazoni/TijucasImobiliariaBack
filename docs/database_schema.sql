-- N:N contrato ↔ inquilinos -------------------------------------------
CREATE TABLE public.contrato_inquilinos (
  contrato_id bigint NOT NULL REFERENCES public.contratos(id) ON DELETE CASCADE,
  usuario_id  bigint NOT NULL REFERENCES public.usuarios(id)  ON DELETE RESTRICT,
  principal   boolean NOT NULL DEFAULT false,
  PRIMARY KEY (contrato_id, usuario_id)
);
CREATE INDEX idx_contrato_inq_usuario ON public.contrato_inquilinos (usuario_id);
CREATE UNIQUE INDEX uq_inquilino_principal
  ON public.contrato_inquilinos (contrato_id) WHERE principal;

-- O índice acima garante "no máximo um". Os gatilhos diferidos abaixo
-- garantem "exatamente um" no COMMIT, permitindo criar o contrato e inserir
-- seus vínculos (ou substituir os vínculos) dentro da mesma transação.
CREATE OR REPLACE FUNCTION public.assert_contrato_tem_um_principal(
  p_contrato_id bigint
)
RETURNS void AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.contratos WHERE id = p_contrato_id)
     AND (
       SELECT count(*)
       FROM public.contrato_inquilinos
       WHERE contrato_id = p_contrato_id AND principal
     ) <> 1 THEN
    RAISE EXCEPTION
      'O contrato % deve possuir exatamente um inquilino principal.',
      p_contrato_id
      USING ERRCODE = '23514';
  END IF;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION public.valida_principal_apos_contrato()
RETURNS trigger AS $$
BEGIN
  PERFORM public.assert_contrato_tem_um_principal(NEW.id);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION public.valida_principal_apos_vinculo()
RETURNS trigger AS $$
BEGIN
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    PERFORM public.assert_contrato_tem_um_principal(NEW.contrato_id);
  END IF;
  IF TG_OP = 'DELETE'
     OR (TG_OP = 'UPDATE' AND OLD.contrato_id <> NEW.contrato_id) THEN
    PERFORM public.assert_contrato_tem_um_principal(OLD.contrato_id);
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER contratos_exigem_inquilino_principal
AFTER INSERT OR UPDATE ON public.contratos
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.valida_principal_apos_contrato();

CREATE CONSTRAINT TRIGGER contrato_inquilinos_exatamente_um_principal
AFTER INSERT OR UPDATE OR DELETE ON public.contrato_inquilinos
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.valida_principal_apos_vinculo();

-- =====================================================================
-- BLOCO 3.1 — GARANTIAS LOCATÍCIAS (Lei 8.245/91, arts. 37 a 42)
-- =====================================================================
-- Modelo supertipo + detalhe. A modalidade da garantia é um RELACIONAMENTO,
-- nunca uma coluna solta em `contratos`.
--
--   garantias
--     ├── garantia_caucao         (1:1)
--     ├── garantia_fiadores       (1:N)
--     └── garantia_seguro_fianca  (1:1)
--
-- Ausência de garantia ATIVA = locação sem garantia (art. 42: nesse caso o
-- locador pode exigir o aluguel até o 6º dia útil do mês vincendo).
-- =====================================================================

CREATE TABLE public.garantias (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contrato_id         bigint NOT NULL REFERENCES public.contratos(id) ON DELETE CASCADE,
  tipo                text   NOT NULL,                   -- CAUCAO | FIADOR | SEGURO_FIANCA
  status              text   NOT NULL DEFAULT 'ATIVA',   -- ATIVA | SUBSTITUIDA | ENCERRADA
  data_inicio         date   NOT NULL DEFAULT CURRENT_DATE,
  data_fim            date   NULL,                       -- preenchida ao substituir/encerrar
  motivo_substituicao text   NULL,                       -- art. 40
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT garantias_tipo_chk   CHECK (tipo IN ('CAUCAO','FIADOR','SEGURO_FIANCA')),
  CONSTRAINT garantias_status_chk CHECK (status IN ('ATIVA','SUBSTITUIDA','ENCERRADA')),
  CONSTRAINT garantias_datas_chk  CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

-- Art. 37, § único: é VEDADA mais de uma modalidade de garantia num mesmo
-- contrato (e exigir duas é contravenção penal — art. 43, II). O índice
-- parcial faz o próprio banco impedir isso.
CREATE UNIQUE INDEX uq_garantia_ativa_por_contrato
  ON public.garantias (contrato_id) WHERE status = 'ATIVA';
CREATE INDEX idx_garantias_contrato ON public.garantias (contrato_id);
CREATE TRIGGER trg_garantias_updated BEFORE UPDATE ON public.garantias
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- CAUÇÃO (art. 38) -----------------------------------------------------
CREATE TABLE public.garantia_caucao (
  garantia_id       bigint PRIMARY KEY REFERENCES public.garantias(id) ON DELETE CASCADE,
  modalidade        text NOT NULL,          -- DINHEIRO | BEM_MOVEL | BEM_IMOVEL | TITULOS
  valor             numeric(12,2) NULL,     -- obrigatório quando DINHEIRO
  -- Dinheiro → caderneta de poupança (art. 38, §2º)
  banco             text NULL,
  agencia           text NULL,
  conta_poupanca    text NULL,
  data_deposito     date NULL,
  comprovante_deposito_key text NULL, -- chave do objeto no S3 privado (nunca URL pública)
  status_pagamento text NOT NULL DEFAULT 'PENDENTE',
  pago_em         timestamptz NULL,
  analisado_por   bigint NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  analisado_em    timestamptz NULL,
  -- Bens (art. 38, §1º): móvel → registro em RTD; imóvel → averbação na matrícula
  descricao_bem     text NULL,
  registro_cartorio text NULL,
  -- Devolução (os rendimentos revertem ao locatário — art. 38, §2º)
  valor_devolvido   numeric(12,2) NULL,
  valor_retido      numeric(12,2) NULL,
  motivo_retencao   text NULL,
  data_devolucao    date NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT caucao_modalidade_chk CHECK (modalidade IN ('DINHEIRO','BEM_MOVEL','BEM_IMOVEL','TITULOS')),
  CONSTRAINT caucao_dinheiro_chk   CHECK (modalidade <> 'DINHEIRO' OR valor IS NOT NULL),
  CONSTRAINT caucao_bem_chk        CHECK (modalidade = 'DINHEIRO' OR descricao_bem IS NOT NULL),
  CONSTRAINT caucao_valores_chk    CHECK (
    (valor           IS NULL OR valor           >= 0) AND
    (valor_devolvido IS NULL OR valor_devolvido >= 0) AND
    (valor_retido    IS NULL OR valor_retido    >= 0)
  ),
  CONSTRAINT caucao_retencao_chk   CHECK (
    valor_retido IS NULL OR valor_retido = 0 OR motivo_retencao IS NOT NULL
  ),
  CONSTRAINT garantia_caucao_status_pagamento_chk CHECK (
    status_pagamento IN ('PENDENTE','EM_ANALISE','PAGO','REJEITADO')
  )
);
CREATE TRIGGER trg_garantia_caucao_updated BEFORE UPDATE ON public.garantia_caucao
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Art. 38, §2º: caução EM DINHEIRO não pode exceder 3 meses de aluguel.
-- Regra cross-table (garantia_caucao → garantias → contratos), logo não cabe
-- num CHECK. O service valida com mensagem amigável; este trigger é a rede de
-- segurança no banco, porque o excesso torna a cláusula nula.
CREATE OR REPLACE FUNCTION valida_caucao_dinheiro()
RETURNS TRIGGER AS $$
DECLARE
  v_aluguel numeric(12,2);
BEGIN
  IF NEW.modalidade = 'DINHEIRO' THEN
    SELECT c.valor_aluguel
      INTO v_aluguel
      FROM public.garantias g
      JOIN public.contratos c ON c.id = g.contrato_id
     WHERE g.id = NEW.garantia_id;

    IF v_aluguel IS NOT NULL AND NEW.valor > (3 * v_aluguel) THEN
      RAISE EXCEPTION
        'Caucao em dinheiro nao pode exceder 3 alugueis (Lei 8.245/91, art. 38, §2º). Maximo: %, informado: %',
        (3 * v_aluguel), NEW.valor
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_caucao_limite_legal
  BEFORE INSERT OR UPDATE ON public.garantia_caucao
  FOR EACH ROW EXECUTE FUNCTION valida_caucao_dinheiro();


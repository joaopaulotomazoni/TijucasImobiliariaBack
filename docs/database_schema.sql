  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parcela_id bigint NOT NULL REFERENCES public.parcelas(id) ON DELETE CASCADE,
  tipo       text   NOT NULL,
  descricao  text   NULL,
  valor      numeric(12,2) NOT NULL,           -- >0 cobrança, <0 desconto
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT lancamento_tipo_chk CHECK (
    tipo IN ('ALUGUEL','CONDOMINIO','IPTU','MULTA','JUROS','DESCONTO','TAXA','OUTRO')
  )
);
CREATE INDEX idx_lancamentos_parcela ON public.parcela_lancamentos (parcela_id);

-- Boletos emitidos para a parcela (suporta 2ª via) --------------------
CREATE TABLE public.boletos (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parcela_id      bigint  NOT NULL REFERENCES public.parcelas(id) ON DELETE CASCADE,
  via             int     NOT NULL DEFAULT 1,
  nosso_numero    text    NULL,
  linha_digitavel text    NULL,
  codigo_barras   text    NULL,
  data_emissao    date    NOT NULL DEFAULT CURRENT_DATE,
  data_vencimento date    NOT NULL,
  valor           numeric(12,2) NOT NULL,
  ativo           boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT boletos_valor_chk CHECK (valor >= 0)
);
CREATE UNIQUE INDEX uq_boleto_ativo_por_parcela
  ON public.boletos (parcela_id) WHERE ativo;
CREATE INDEX idx_boletos_parcela ON public.boletos (parcela_id);

-- Pagamentos (múltiplos por parcela => pagamento parcial) -------------
CREATE TABLE public.pagamentos (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parcela_id      bigint NOT NULL REFERENCES public.parcelas(id) ON DELETE RESTRICT,
  boleto_id       bigint NULL REFERENCES public.boletos(id) ON DELETE SET NULL,
  valor_pago      numeric(12,2) NOT NULL,
  data_pagamento  date   NOT NULL DEFAULT CURRENT_DATE,
  forma_pagamento text   NOT NULL,
  comprovante_url text   NULL,
  registrado_por  bigint NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pagamentos_forma_chk CHECK (
    forma_pagamento IN ('PIX','BOLETO','TRANSFERENCIA','DINHEIRO','CARTAO')
  ),
  CONSTRAINT pagamentos_valor_chk CHECK (valor_pago > 0)
);
CREATE INDEX idx_pagamentos_parcela ON public.pagamentos (parcela_id);


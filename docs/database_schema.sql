-- BLOCO 5 — INTEGRAÇÃO COM O GATEWAY DE PAGAMENTO (Asaas)
-- =====================================================================
-- migration 004. Ver docs/plano-financeiro-adaptado.md e
-- asaas-split-subcontas.md (repo frontend) para o desenho completo.
--
-- Desenhado em duas fases:
--   Fase 1 (MVP) — recebimento na conta principal; `contas_gateway` e
--     `splits` não são usadas; repasse manual/Pix registrado em `repasses`
--     com conta_gateway_id NULL.
--   Fase 2 — split automático via subconta do proprietário, liberado só
--     depois do período de avaliação regulatória do Banco Central
--     (Resolução Conjunta nº 16/17: até 10 subcontas, R$ 2.000 emitidos
--     por subconta, 60 dias).
-- =====================================================================

-- Locatário como "customer" no gateway ---------------------------------
CREATE TABLE public.gateway_customers (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id           bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  gateway              text   NOT NULL DEFAULT 'ASAAS',
  external_customer_id text   NOT NULL,
  created_at           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_gateway_customer UNIQUE (usuario_id, gateway)
);
CREATE UNIQUE INDEX uq_gateway_customer_external
  ON public.gateway_customers (gateway, external_customer_id);

-- Subconta BaaS do proprietário — destino do split (Fase 2) ------------
-- Fluxo obrigatório de criação: (1) INSERT aqui com status='PENDENTE' e
-- external_reference próprio; (2) POST no gateway enviando essa referência;
-- (3) UPDATE com external_account_id/wallet_id/api_key_encrypted. A apiKey
-- da subconta é retornada UMA ÚNICA VEZ e não tem endpoint de recuperação —
-- se o passo 2 der certo e o 3 falhar, a external_reference permite
-- reconciliar em vez de criar outra subconta.
CREATE TABLE public.contas_gateway (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id          bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  gateway             text   NOT NULL DEFAULT 'ASAAS',
  external_reference  text   NOT NULL,
  external_account_id text   NULL,
  wallet_id           text   NULL,
  -- NUNCA em texto puro, nunca em log, nunca em resposta de API ao frontend.
  api_key_encrypted   text   NULL,
  status              text   NOT NULL DEFAULT 'PENDENTE',
  onboarding_status   text   NULL,
  onboarding_url      text   NULL,   -- link de envio de documentos (reenviável)
  aprovada_em         timestamptz NULL,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_conta_gateway     UNIQUE (usuario_id, gateway),
  CONSTRAINT uq_conta_gateway_ref UNIQUE (gateway, external_reference),
  CONSTRAINT conta_gateway_status_chk CHECK (
    status IN ('PENDENTE','APROVADA','BLOQUEADA','RECUSADA')
  ),
  -- Só uma subconta APROVADA pode receber split, e para isso precisa da
  -- wallet e da chave — impede UPDATE parcial deixar o registro incompleto
  -- num estado que o código a jusante trataria como pronto.
  CONSTRAINT conta_gateway_aprovada_chk CHECK (
    status <> 'APROVADA'
    OR (external_account_id IS NOT NULL
        AND wallet_id IS NOT NULL
        AND api_key_encrypted IS NOT NULL)
  )
);
CREATE TRIGGER trg_contas_gateway_updated BEFORE UPDATE ON public.contas_gateway
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Espelho da parcela (cobrança) no gateway — fonte da verdade da 2ª via
CREATE TABLE public.gateway_cobrancas (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parcela_id          bigint NOT NULL REFERENCES public.parcelas(id) ON DELETE CASCADE,
  gateway             text   NOT NULL DEFAULT 'ASAAS',
  external_payment_id text   NOT NULL,
  linha_digitavel     text   NULL,
  codigo_barras       text   NULL,
  url_boleto          text   NULL,
  url_fatura          text   NULL,
  qr_code_pix         text   NULL,
  copia_cola_pix      text   NULL,
  valor               numeric(12,2) NOT NULL,
  data_vencimento     date   NOT NULL,
  status_gateway      text   NULL,   -- vocabulário do gateway, sem tradução
  raw_json            jsonb  NULL,   -- resposta crua, para auditoria
  ativa               boolean NOT NULL DEFAULT true,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT gateway_cobranca_valor_chk CHECK (valor >= 0)
);
-- Uma parcela acumula cobranças ao longo do tempo (reemissão por reajuste),
-- mas só UMA pode estar ativa — duas vivas significa cobrar em dobro.
CREATE UNIQUE INDEX uq_gateway_cobranca_ativa

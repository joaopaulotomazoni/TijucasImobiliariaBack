-- =====================================================================
-- SISTEMA DE GERENCIAMENTO DE ALUGUÉIS — MODELO REFATORADO (PostgreSQL)
-- Variante: PESSOA + USUÁRIO em uma única tabela (`usuarios`)
-- =====================================================================
-- Convenções:
--   - PK bigint identity (compatível com o schema atual).
--   - Dinheiro em numeric(12,2). Nunca float.
--   - Enums via text + CHECK. Troque por CREATE TYPE ... AS ENUM se
--     quiser tipagem forte no banco.
--   - `usuarios` guarda cadastro + autenticação. senha_hash/perfil são
--     NULL para quem não loga (proprietário, fiador). A identidade real
--     da linha é `documento`. Papéis de negócio (proprietário/inquilino/
--     fiador) são RELACIONAMENTOS, nunca colunas booleanas.
-- =====================================================================

-- =====================================================================
-- RESET — apaga TODAS as tabelas deste modelo (e TODOS os dados!).
-- Destrutivo e irreversível. Roda antes de recriar tudo do zero.
-- CASCADE derruba FKs, índices e triggers dependentes junto.
-- =====================================================================

-- USUARIOS = cadastro (party) + autenticação, numa tabela só ----------
CREATE TABLE public.usuarios (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Cadastro (todo proprietário, inquilino, fiador e corretor é uma linha aqui)
  nome_completo     text    NOT NULL,          -- razão social se PJ
  documento         text    NOT NULL,          -- CPF/CNPJ: só dígitos
  -- Derivado do documento: 14 dígitos = CNPJ = PJ; senão PF
  tipo_pessoa       text    GENERATED ALWAYS AS (
                      CASE WHEN length(documento) = 14 THEN 'PJ' ELSE 'PF' END
                    ) STORED,
  rg                text    NULL,              -- RG (PF); opcional
  email             text    NULL,              -- contato + login
  telefone          text    NULL,
  data_nascimento   date    NULL,
  endereco_id       bigint  NULL REFERENCES public.enderecos(id) ON DELETE SET NULL,
  -- Autenticação (NULL para quem não loga)
  senha_hash        text    NULL,
  perfil            text    NULL,              -- ADMIN/CORRETOR/CLIENTE
  email_verificado  boolean NOT NULL DEFAULT false,
  ultimo_login      timestamptz NULL,
  ativo             boolean NOT NULL DEFAULT true,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT usuarios_documento_key UNIQUE (documento),
  CONSTRAINT usuarios_email_key     UNIQUE (email),
  CONSTRAINT usuarios_telefone_key  UNIQUE (telefone),
  CONSTRAINT usuarios_doc_chk    CHECK (documento ~ '^[0-9]+$' AND length(documento) IN (11,14)),
  CONSTRAINT usuarios_perfil_chk CHECK (perfil IS NULL OR perfil IN ('ADMIN','CORRETOR','CLIENTE')),
  CONSTRAINT usuarios_login_chk  CHECK (senha_hash IS NULL OR email IS NOT NULL)
);
CREATE TRIGGER trg_usuarios_updated BEFORE UPDATE ON public.usuarios
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

